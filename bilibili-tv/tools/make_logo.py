"""
Renders src/fonts/bilibili.svg (the Simple Icons "Bilibili" mark, CC0) in the brand blue at the given
size and writes src/logo.c: an LVGL ARGB8888 image (needs cairosvg and pillow).

  tools/make_logo.py [size] [out.c]
"""
import io, os, sys
import cairosvg
from PIL import Image

size = int(sys.argv[1]) if len(sys.argv) > 1 else 48
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "src", "logo.c")
svg = open(os.path.join(os.path.dirname(__file__), "..", "src", "fonts", "bilibili.svg")).read()
svg = svg.replace("<svg ", '<svg fill="#00A1D6" ', 1)
png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
im = Image.open(io.BytesIO(png)).convert("RGBA")
px = im.load()
rows = []
for y in range(size):
    row = []
    for x in range(size):
        r, g, b, a = px[x, y]
        # LVGL ARGB8888 in memory: B, G, R, A
        row += [b, g, r, a]
    rows.append(row)
data = [v for r in rows for v in r]
with open(out, "w") as f:
    f.write("/* generated by tools/make_logo.py, do not edit */\n\n#include <lvgl.h>\n\n")
    f.write("static const uint8_t logo_map[] = {\n")
    for i in range(0, len(data), 16):
        f.write("\t" + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ",\n")
    f.write("};\n\n")
    f.write("const lv_image_dsc_t ui_logo = {\n\t.header = {\n\t\t.magic = LV_IMAGE_HEADER_MAGIC,\n"
            "\t\t.cf = LV_COLOR_FORMAT_ARGB8888,\n\t\t.w = %d,\n\t\t.h = %d,\n\t\t.stride = %d,\n\t},\n"
            "\t.data_size = sizeof(logo_map),\n\t.data = logo_map,\n};\n" % (size, size, size * 4))
print("wrote", out, size)
