"""
Writes src/ui/pinyin_dict.c, the dictionary of the pinyin input method of LVGL: one entry per toneless
syllable, the hanzi of that syllable by falling frequency. Only characters that the firmware font has.

  tools/make_pinyin_dict.py [--max 120]

The input method takes the first entry that starts with the typed letters, so the entries are sorted by
syllable and "ni" comes before "nian". It handles single characters only. Needs pypinyin, jieba and
fontTools (pip install --target tools-local/pylib pypinyin jieba fonttools).
"""
import argparse, os, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.abspath(os.path.join(HERE, "../../.."))
sys.path.insert(0, os.path.join(WS, "tools-local/pylib"))
ap = argparse.ArgumentParser()
ap.add_argument("--max", type=int, default=120, help="most characters per syllable")
ap.add_argument("--font", default=os.path.join(HERE, "../src/ui/fonts/NotoSansSC-subset.ttf"))
ap.add_argument("-o", default=os.path.join(HERE, "../src/ui/pinyin_dict.c"))
a = ap.parse_args()

import jieba, pypinyin
from fontTools.ttLib import TTFont

cmap = TTFont(a.font).getBestCmap()

# single character frequencies from the dictionary of jieba
freq = collections.Counter()
with open(os.path.join(os.path.dirname(jieba.__file__), "dict.txt"), encoding="utf-8") as f:
    for line in f:
        w = line.split()
        if len(w) >= 2 and len(w[0]) == 1:
            freq[w[0]] = int(w[1])

by_syllable = collections.defaultdict(list)
for cp in range(0x4E00, 0xA000):
    ch = chr(cp)
    if cp not in cmap:
        continue
    for readings in pypinyin.pinyin(ch, style=pypinyin.Style.NORMAL, heteronym=True, errors="ignore"):
        for r in readings:
            r = r.replace("ü", "v")
            if r.isascii() and r.isalpha():
                by_syllable[r].append(ch)

# the input method refuses to start a syllable with i, u or v; none of them does
assert not [s for s in by_syllable if s[0] in "iuv"], "syllable starts with i/u/v"

lines = []
total = 0
for syl in sorted(by_syllable):
    chars = sorted(set(by_syllable[syl]), key=lambda c: (-freq[c], c))[:a.max]
    total += len(chars)
    lines.append('\t{"%s", "%s"},' % (syl, "".join(chars)))

with open(a.o, "w", encoding="utf-8") as f:
    f.write("/*\n * Copyright (c) 2026 Yuzuki Tsuru\n *\n * SPDX-License-Identifier: Apache-2.0\n */\n\n")
    f.write("/* Generated by tools/make_pinyin_dict.py, do not edit. */\n\n")
    f.write("#include <lvgl.h>\n\n#include \"pinyin_dict.h\"\n\n")
    f.write("const lv_pinyin_dict_t bili_pinyin_dict[] = {\n")
    f.write("\n".join(lines))
    f.write("\n\t{NULL, NULL},\n};\n")
print("%s: %d syllables, %d characters, %d bytes" % (os.path.relpath(a.o), len(lines), total, os.path.getsize(a.o)))
print("most used:", ", ".join("%s(%d)" % (s, len(by_syllable[s])) for s, _ in sorted(((s, len(set(c))) for s, c in by_syllable.items()), key=lambda x: -x[1])[:6]))
